-- Українське сортування імен гостей.
--
-- Навіщо: із колацією за замовчуванням PostgreSQL сортує латиницю перед
-- кирилицею, а «І» (U+0406) ставить перед «А» — тобто список гостей,
-- відсортований за іменем, виглядав би для українця випадковим:
--   Developer, Ігор, Андрій, Богдана...
-- З колацією uk-UA-x-icu порядок стає очікуваним: Андрій, Богдана, ..., Ігор.
--
-- Колація задається на САМІЙ КОЛОНЦІ, тому звичайний ORDER BY name у Prisma
-- одразу сортує правильно й не потрібні сирі запити.
--
-- Написано вручну: Prisma не описує колації в схемі (і не бачить їх при
-- порівнянні, тому drift ця міграція не створює).
--
-- DO-блок, а не простий ALTER: колації ICU є лише в збірках PostgreSQL з ICU
-- (офіційні образи — з ним). На збірці без ICU міграція просто нічого не
-- зробить, замість того щоб упасти й зламати розгортання.
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_collation WHERE collname = 'uk-UA-x-icu') THEN
    EXECUTE 'ALTER TABLE "guests" ALTER COLUMN "name" TYPE VARCHAR(100) COLLATE "uk-UA-x-icu"';
  ELSE
    RAISE NOTICE 'Колація uk-UA-x-icu недоступна — сортування імен лишається стандартним';
  END IF;
END $$;
