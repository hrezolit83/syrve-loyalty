-- Рядки, записані до появи колонки when_created, не мають часу операції.
-- Статистика й журнал транзакцій сортують і фільтрують саме за ним, тому
-- без цього вони опинилися б у кінці списку й поза будь-яким періодом.
-- Найкраще наближення, яке ми маємо для таких рядків, — час запису:
-- поллер бачить транзакцію із затримкою не більшою за POLL_INTERVAL_SEC.
-- Справжній час із Syrve підставить бекфіл історії, коли його запустять.
UPDATE "processed_transactions"
   SET "when_created" = "created_at"
 WHERE "when_created" IS NULL;
